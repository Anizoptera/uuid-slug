/**
 * Render the competitor matrix records as the Markdown report tracked under `bench/results/`.
 *
 * The report is generated, never edited: every figure comes from the records that
 * `generation-matrix.ts` emits, so re-running that driver replaces the file and a stale report
 * shows its own date. Each verdict compares the exact 95% intervals of two median costs: "leads"
 * and "trails" mean the intervals do not overlap, "unresolved" means they do. That keeps the
 * verdict mechanical; nobody reads a ratio and decides by eye.
 */

export interface ReportMeasurement {
  readonly comparable: string;
  readonly implementation: string;
  readonly kind: "measurement";
  readonly median95?: readonly [number, number];
  readonly medianNs: number;
  readonly name: string;
  readonly qualification: "qualified" | "rejected";
  readonly runtime: string;
}

export interface ReportExclusion {
  readonly kind: "rejection" | "unsupported";
  readonly name: string;
  readonly reason: string;
  readonly runtime: string;
}

export type ReportRecord =
  | ReportMeasurement
  | ReportExclusion
  | { readonly kind: string; readonly runtime: string };

export interface ReportOptions {
  readonly durationMs: number;
  /** ISO date of the run; provenance the reader needs to judge how stale the figures are. */
  readonly generatedOn: string;
  readonly machine: string;
  readonly samples: number;
  readonly warmupMs: number;
}

export type Verdict = "leads" | "trails" | "unresolved";

/** Compare two median intervals; overlapping intervals prove nothing either way. */
export function verdict(subject: ReportMeasurement, reference: ReportMeasurement): Verdict {
  if (!subject.median95 || !reference.median95) return "unresolved";
  if (subject.median95[1] < reference.median95[0]) return "leads";
  if (subject.median95[0] > reference.median95[1]) return "trails";
  return "unresolved";
}

const isMeasurement = (record: ReportRecord): record is ReportMeasurement =>
  record.kind === "measurement";
const isExclusion = (record: ReportRecord): record is ReportExclusion =>
  record.kind === "rejection" || record.kind === "unsupported";
const fastest = (rows: readonly ReportMeasurement[]): ReportMeasurement | undefined =>
  rows.reduce<ReportMeasurement | undefined>(
    (best, row) => (best === undefined || row.medianNs < best.medianNs ? row : best),
    undefined,
  );
const ratio = (subject: ReportMeasurement, reference: ReportMeasurement): string =>
  (subject.medianNs / reference.medianNs).toFixed(2);
const code = (text: string): string => `\`${text}\``;

/** Render the report; throws when no runtime produced a qualified package row. */
export function renderGenerationReport(
  records: readonly ReportRecord[],
  options: ReportOptions,
): string {
  const measurements = records.filter(isMeasurement);
  const runtimes = [...new Set(measurements.map(({ runtime }) => runtime))];
  if (runtimes.length === 0) throw new Error("No measurements to report");
  const lines: string[] = [
    "# UUID generation across runtimes",
    "",
    "Generated by `bun run bench:results`; do not edit. Re-run it after a runtime, competitor, or",
    "package change so the figures below describe the current code.",
    "",
    `Run on ${options.generatedOn} (${options.machine}). Runtimes: ${runtimes.join(", ")}.`,
    `${String(options.samples)} samples of ${String(options.durationMs)} ms per case after`,
    `${String(options.warmupMs)} ms warm-up, one process per runtime, cases run one at a time.`,
    "",
    "How to read it: the ratio is the package's median cost per call divided by the fastest other",
    "row, so below 1 means the package is faster. A verdict compares the exact 95% intervals of the",
    'two medians: "leads" and "trails" mean the intervals do not overlap; "unresolved" means they',
    "do, and one run cannot separate the rows. Platform rows are the runtime's own primitive; the",
    "package validates its output and returns typed errors, so that column is a floor, not a rival.",
    "Figures are one machine's and move between engine versions: read the direction of each",
    "difference, not its digits.",
    "",
  ];
  for (const runtime of runtimes) {
    const rows = measurements.filter((row) => row.runtime === runtime);
    // eslint-disable-next-line unicorn/no-array-sort -- Sort owned storage within the ES2022 type baseline.
    const groups = [...new Set(rows.map(({ comparable }) => comparable))].sort();
    const table: string[] = [];
    const counts = { leads: 0, trails: 0, unresolved: 0 };
    const trailing: string[] = [];
    for (const group of groups) {
      const qualified = rows.filter(
        (row) => row.comparable === group && row.qualification === "qualified",
      );
      const subject = fastest(qualified.filter(({ name }) => name.startsWith("package.")));
      const rival = fastest(
        qualified.filter(
          ({ name }) => !name.startsWith("package.") && !name.startsWith("platform."),
        ),
      );
      const platform = fastest(qualified.filter(({ name }) => name.startsWith("platform.")));
      if (!subject || (!rival && !platform)) continue;
      const outcome = rival ? verdict(subject, rival) : "unresolved";
      if (rival) counts[outcome] += 1;
      if (outcome === "trails") trailing.push(group);
      table.push(
        `| ${code(group)} | ${code(subject.name)} | ${
          rival ? `${code(rival.name)} | ${ratio(subject, rival)} | ${outcome}` : "none | | "
        } | ${platform ? ratio(subject, platform) : ""} |`,
      );
    }
    if (table.length === 0) continue;
    lines.push(
      `## ${runtime}`,
      "",
      `Against the fastest package: leads ${String(counts.leads)}, trails ${String(counts.trails)}, unresolved ${String(counts.unresolved)}${
        trailing.length ? `. Trails on ${trailing.map(code).join(", ")}` : ""
      }.`,
      "",
      "| Group | Package route | Fastest package | Ratio | Verdict | Ratio to platform |",
      "| --- | --- | --- | ---: | --- | ---: |",
      ...table,
      "",
    );
  }
  const exclusions = new Map<string, { reason: string; runtimes: string[] }>();
  for (const record of records.filter(isExclusion)) {
    const entry = exclusions.get(record.name) ?? { reason: record.reason, runtimes: [] };
    entry.runtimes.push(record.runtime);
    exclusions.set(record.name, entry);
  }
  if (exclusions.size > 0)
    lines.push(
      "## Timed but not ranked",
      "",
      "These rows stay in the raw records so a faster mechanism is never hidden, but they cannot",
      "win a group: each gave up something the package guarantees, or cannot run on that runtime.",
      "",
      "| Row | Why | Runtimes |",
      "| --- | --- | --- |",
      ...[...exclusions].map(
        ([name, { reason, runtimes: seen }]) =>
          `| ${code(name)} | ${reason} | ${seen.join(", ")} |`,
      ),
      "",
    );
  return lines.join("\n");
}
