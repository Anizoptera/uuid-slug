/**
 * Write the tracked benchmark reports under `bench/results/`.
 *
 * `bench/reports/` is ignored by git and holds profiling artifacts nobody diffs. These files are
 * tracked on purpose: a report git tracks shows its own date, changes only when this command runs,
 * and lets a reviewer diff two runs, while a hand-pasted snapshot rots behind a date that still
 * looks fresh. Nothing here is typed in. Every figure comes from the two drivers this file spawns,
 * so there is no prose to go stale. `bench/PERFORMANCE.md` owns conclusions; these files are its
 * evidence, never claims of their own.
 *
 * Full runs only, so there is no `--smoke`. Smoke settings rank nothing, and the paired runs in
 * `bench/PERFORMANCE.md` show smoke disagreeing with full runs by tens of percent on some routes;
 * a smoke report in a tracked file would be read as a result.
 */
import { mkdir } from "node:fs/promises";
import { arch, cpus, platform, release } from "node:os";
import { join } from "node:path";

import { renderGenerationReport } from "./generation-report";
import type { ReportRecord } from "./generation-report";

if (process.argv.includes("--smoke"))
  throw new Error(
    "bench:results writes full runs only; check wiring with bench:matrix --smoke or bench:competitors --smoke",
  );

const project = join(import.meta.dir, "..");
const results = join(import.meta.dir, "results");
if (!process.env.UUID_SLUG_BENCH_NODE_CURRENT_EXECUTABLE)
  throw new Error(
    "Set UUID_SLUG_BENCH_NODE_CURRENT_EXECUTABLE to Node Current so tracked results include it beside Node LTS",
  );

/** The competitor driver's full-run settings, passed down so the report states what actually ran. */
const competitors = { durationMs: 20, samples: 9, warmupMs: 32 };

/** Randomness samples per candidate for the package matrix; `bench/matrix.ts` uses the same count. */
const entropySamples = 50_000;

const machine = `${cpus()[0]?.model ?? arch()}, ${platform()} ${release()}`;
const generatedOn = new Date().toISOString().slice(0, 10);

/** Run a driver to completion. A failed driver writes nothing, so a stale file cannot pass as fresh. */
async function drive(
  command: readonly string[],
  label: string,
  env: Readonly<Record<string, string>> = {},
): Promise<string> {
  const child = Bun.spawn([...command], {
    cwd: project,
    env: { ...process.env, ...env },
    stderr: "inherit",
    stdout: "pipe",
    timeout: 5 * 60_000,
  });
  const [stdout, status] = await Promise.all([new Response(child.stdout).text(), child.exited]);
  if (status !== 0) throw new Error(`${label} exited ${String(status)}`);
  return stdout;
}

/** Add stable report context to the Markdown emitted by the matrix driver. */
function matrixReport(output: string): string {
  const lines: string[] = [
    "# Package throughput and randomness across runtimes",
    "",
    "Generated by `bun run bench:results`; do not edit.",
    "",
    `Run on ${generatedOn} (${machine}). One process per runtime. Node runs a bundle of the benchmark`,
    "source because its resolver rejects extensionless TypeScript imports; Bun runs the source, so",
    "inlining can differ between the two columns. Figures are one machine's and move a few percent",
    "per run: read ratios, not digits.",
    "",
    "Throughput is operations per second in millions, with one byte of every result consumed so the",
    "call cannot be optimised away. Rows named `package.*` are this package; the other rows are",
    "competitor packages and the runtime's own functions, listed for the cost of the same surface.",
    "",
    `Randomness uses ${String(entropySamples)} samples per candidate per runtime; the method and its`,
    "limits are in `bench/entropy.ts`.",
    "",
    "- `distinct`: different 74-bit UUIDv7 payloads observed. A repeat within the sample would show here.",
    "- `in-tick`: consecutive values inside one millisecond that strictly increase, over",
    "  same-millisecond pairs only. Pairs that span a tick order by timestamp whatever the generator",
    "  does, so counting them would measure the clock.",
    "- `peak/ms`: most values sharing an encoded timestamp; it does not measure wall-clock draw rate.",
    "- `encoded − end/ms`: largest encoded timestamp minus the wall clock immediately after drawing.",
    "- `Δclock/ms`: wall-clock change across the burst; endpoint reads do not prove a monotonic clock.",
    "- `counter`: width of a leading counter advancing by exactly one, with the share of pairs",
    "  obeying it. It says nothing about how many bits an attacker can predict.",
    "- `P(1) range`: narrowest and widest share of ones across the 74 payload bits.",
    "",
    'An entropy source of "unobserved" means the draw happens below JavaScript or the library',
    "captured its source before instrumentation; it states what was seen, not a finding.",
    "",
    "Not covered: memory and allocation, multi-core contention, cold start, megamorphic call sites,",
    "and randomness quality beyond these measures; that needs a battery such as PractRand.",
  ];
  lines.push("", output.trim());
  return `${lines.join("\n")}\n`;
}

interface RustTimingRecord {
  readonly kind: "measurement" | "contention";
  readonly name: string;
  readonly version: number;
  readonly round: number;
  readonly calls: number;
  readonly nsPerCall: number;
  readonly run: number;
  readonly batchSize?: number;
  readonly threads?: number;
}

type RustTimingInput = Omit<RustTimingRecord, "run">;

interface RustTargetRecord {
  readonly kind: "target";
  readonly name: string;
  readonly target: string;
  readonly supported: boolean;
  readonly diagnostic?: string;
}

function sorted<Value>(
  values: readonly Value[],
  compare: (left: Value, right: Value) => number,
): Value[] {
  const result: Value[] = [];
  for (const value of values) {
    const index = result.findIndex((existing) => compare(value, existing) < 0);
    result.splice(index < 0 ? result.length : index, 0, value);
  }
  return result;
}

function median(values: readonly number[]): number {
  const ordered = sorted(values, (left, right) => left - right);
  const value = ordered[Math.floor(ordered.length / 2)];
  if (value === undefined) throw new Error("cannot take the median of an empty sample");
  return value;
}

type JsonRecord = Record<string, string | number | boolean | object>;

function parseJsonLines(output: string): JsonRecord[] {
  return output
    .trim()
    .split("\n")
    .map((line) => JSON.parse(line) as JsonRecord);
}

function isRustTiming(record: JsonRecord): record is JsonRecord & RustTimingInput {
  return (
    (record.kind === "measurement" || record.kind === "contention") &&
    typeof record.name === "string" &&
    typeof record.version === "number" &&
    typeof record.round === "number" &&
    typeof record.calls === "number" &&
    typeof record.nsPerCall === "number"
  );
}

function isRustTarget(record: JsonRecord): record is JsonRecord & RustTargetRecord {
  return (
    record.kind === "target" &&
    typeof record.name === "string" &&
    typeof record.target === "string" &&
    typeof record.supported === "boolean"
  );
}

function hasCompleteTargetPairs(records: readonly RustTargetRecord[]): boolean {
  const targetsByName = new Map<string, Set<string>>();
  for (const record of records) {
    const targets = targetsByName.get(record.name) ?? new Set<string>();
    targets.add(record.target);
    targetsByName.set(record.name, targets);
  }
  return (
    targetsByName.size > 0 &&
    [...targetsByName.values()].every(
      (targets) =>
        targets.size === 2 && targets.has("native") && targets.has("wasm32-unknown-unknown"),
    ) &&
    records.length === targetsByName.size * 2
  );
}

function renderRustReport(
  timings: readonly RustTimingRecord[],
  targets: readonly RustTargetRecord[],
): string {
  const lines = [
    "# Rust generator matrix",
    "",
    "Generated by `bun run bench:results`; do not edit. The timing table combines five rounds from",
    "each of three fresh processes. The target table compiles the actual generation call in an",
    "isolated consumer with the crate's selected features and caller-selected WebAssembly entropy",
    "backends. Unsupported means that strongest tested configuration did not compile.",
    "",
    `Run on ${generatedOn} (${machine}). Different entropy, ordering, state-sharing, allocation, and`,
    "output contracts are not ranked as interchangeable. Figures are one machine's; read repeated",
    "direction, not digits.",
    "",
    "## Throughput",
    "",
    "| Call | Mode | UUID | Median ns/call | Observed range |",
    "| --- | --- | ---: | ---: | ---: |",
  ];
  const names = sorted([...new Set(timings.map((record) => record.name))], (left, right) =>
    left.localeCompare(right),
  );
  for (const name of names) {
    const rows = timings.filter((record) => record.name === name);
    const values = rows.map((record) => record.nsPerCall);
    const first = rows[0];
    if (first === undefined) continue;
    const mode =
      first.kind === "contention"
        ? `${String(first.threads)} threads`
        : first.batchSize === undefined
          ? "scalar"
          : `batch ${String(first.batchSize)}`;
    lines.push(
      `| \`${name}\` | ${mode} | v${String(first.version)} | ${median(values).toFixed(2)} | ${Math.min(...values).toFixed(2)}–${Math.max(...values).toFixed(2)} |`,
    );
  }
  lines.push(
    "",
    "## Compile targets",
    "",
    "| Crate | Native | wasm32-unknown-unknown |",
    "| --- | --- | --- |",
  );
  const crates = sorted([...new Set(targets.map((record) => record.name))], (left, right) =>
    left.localeCompare(right),
  );
  for (const name of crates) {
    const rows = targets.filter((record) => record.name === name);
    const cell = (target: string): string => {
      const row = rows.find((record) => record.target === target);
      if (row === undefined) throw new Error(`${name} did not report ${target}`);
      return row.supported ? "supported" : `unsupported: ${row.diagnostic ?? "cargo check failed"}`;
    };
    lines.push(`| \`${name}\` | ${cell("native")} | ${cell("wasm32-unknown-unknown")} |`);
  }
  return `${lines.join("\n")}\n`;
}

await mkdir(results, { recursive: true });

const competitorLines = await drive(
  ["bun", join(import.meta.dir, "generation-matrix.ts")],
  "generation-matrix.ts",
  {
    UUID_SLUG_GENERATION_MS: String(competitors.durationMs),
    UUID_SLUG_GENERATION_SAMPLES: String(competitors.samples),
    UUID_SLUG_GENERATION_WARMUP_MS: String(competitors.warmupMs),
  },
);
const records = competitorLines
  .trim()
  .split("\n")
  .map((line): ReportRecord => JSON.parse(line) as ReportRecord);
await Bun.write(join(results, "competitors.jsonl"), competitorLines);
await Bun.write(
  join(results, "competitors.md"),
  `${renderGenerationReport(records, { ...competitors, generatedOn, machine })}\n`,
);

const matrixLines = await drive(["bun", join(import.meta.dir, "matrix.ts")], "matrix.ts", {
  UUID_SLUG_ENTROPY_SAMPLES: String(entropySamples),
});
await Bun.write(join(results, "matrix.md"), matrixReport(matrixLines));

const rustRuns: RustTimingRecord[] = [];
const rustRaw: JsonRecord[] = [];
let expectedRustNames: readonly string[] | undefined;
for (let run = 0; run < 3; run++) {
  const output = await drive(
    [
      "cargo",
      "run",
      "--manifest-path",
      join(import.meta.dir, "rust-competitors/Cargo.toml"),
      "--release",
      "--locked",
    ],
    "Rust competitor matrix",
    { CARGO_TARGET_DIR: join(project, "rust/target/competitors") },
  );
  const rustRecords = parseJsonLines(output);
  if (rustRecords.filter((record) => record.complete === true).length !== 1)
    throw new Error(`Rust competitor run ${String(run + 1)} did not complete exactly once`);
  if (
    rustRecords.filter((record) => record.kind === "behavior" && record.validated === true)
      .length !== 1
  )
    throw new Error(
      `Rust competitor run ${String(run + 1)} did not validate behavior exactly once`,
    );
  const timings = rustRecords.filter(isRustTiming);
  const counts = new Map<string, number>();
  for (const record of timings) counts.set(record.name, (counts.get(record.name) ?? 0) + 1);
  const names = sorted([...counts.keys()], (left, right) => left.localeCompare(right));
  if ([...counts.values()].some((count) => count !== 5))
    throw new Error(`Rust competitor run ${String(run + 1)} did not report five rounds per call`);
  if (expectedRustNames !== undefined && names.join("\n") !== expectedRustNames.join("\n"))
    throw new Error(`Rust competitor run ${String(run + 1)} reported a different call set`);
  expectedRustNames = names;
  for (const record of rustRecords) record.run = run;
  for (const record of timings) rustRuns.push({ ...record, run });
  rustRaw.push(...rustRecords);
}

const targetOutput = await drive(
  ["bun", join(import.meta.dir, "rust-competitors/target-probes.ts")],
  "Rust target matrix",
);
const targetRecords = parseJsonLines(targetOutput);
const targets = targetRecords.filter(isRustTarget);
if (
  !hasCompleteTargetPairs(targets) ||
  targetRecords.filter((record) => record.kind === "target-complete" && record.complete === true)
    .length !== 1
)
  throw new Error("Rust target matrix is incomplete or duplicated");
await Bun.write(
  join(results, "rust-competitors.jsonl"),
  `${[...rustRaw, ...targetRecords].map((record) => JSON.stringify(record)).join("\n")}\n`,
);
await Bun.write(join(results, "rust-competitors.md"), renderRustReport(rustRuns, targets));

console.log(
  `wrote ${results}/competitors.md, competitors.jsonl, matrix.md, rust-competitors.md, rust-competitors.jsonl`,
);
