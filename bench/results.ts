/**
 * Write the tracked benchmark reports under `bench/results/`.
 *
 * `bench/reports/` is ignored by git and holds profiling artifacts nobody diffs. These files are
 * tracked on purpose: a report git tracks shows its own date, changes only when this command runs,
 * and lets a reviewer diff two runs, while a hand-pasted snapshot rots behind a date that still
 * looks fresh. Nothing here is typed in. Every figure comes from the two drivers this file spawns,
 * so there is no prose to go stale. `bench/PERFORMANCE.md` owns conclusions; these files are its
 * evidence, never claims of their own.
 *
 * Full runs only, so there is no `--smoke`. Smoke settings rank nothing, and the paired runs in
 * `bench/PERFORMANCE.md` show smoke disagreeing with full runs by tens of percent on some routes;
 * a smoke report in a tracked file would be read as a result.
 */
import { mkdir } from "node:fs/promises";
import { arch, cpus, platform, release } from "node:os";
import { join } from "node:path";

import { renderGenerationReport } from "./generation-report";
import type { ReportRecord } from "./generation-report";

if (process.argv.includes("--smoke"))
  throw new Error(
    "bench:results writes full runs only; check wiring with bench:matrix --smoke or bench:competitors --smoke",
  );

const project = join(import.meta.dir, "..");
const results = join(import.meta.dir, "results");

/** The competitor driver's full-run settings, passed down so the report states what actually ran. */
const competitors = { durationMs: 20, samples: 9, warmupMs: 32 };

/** Randomness samples per candidate for the package matrix; `bench/matrix.ts` uses the same count. */
const entropySamples = 50_000;

const machine = `${cpus()[0]?.model ?? arch()}, ${platform()} ${release()}`;
const generatedOn = new Date().toISOString().slice(0, 10);

/** Run a driver to completion. A failed driver writes nothing, so a stale file cannot pass as fresh. */
async function drive(script: string, env: Readonly<Record<string, string>>): Promise<string> {
  const child = Bun.spawn(["bun", join(import.meta.dir, script)], {
    cwd: project,
    env: { ...process.env, ...env },
    stderr: "inherit",
    stdout: "pipe",
    timeout: 20 * 60_000,
  });
  const [stdout, status] = await Promise.all([new Response(child.stdout).text(), child.exited]);
  if (status !== 0) throw new Error(`${script} exited ${String(status)}`);
  return stdout;
}

/** Add stable report context to the Markdown emitted by the matrix driver. */
function matrixReport(output: string): string {
  const lines: string[] = [
    "# Package throughput and randomness across runtimes",
    "",
    "Generated by `bun run bench:results`; do not edit. Re-run it after a runtime, competitor, or",
    "package change so the figures below describe the current code.",
    "",
    `Run on ${generatedOn} (${machine}). One process per runtime. Node runs a bundle of the benchmark`,
    "source because its resolver rejects extensionless TypeScript imports; Bun runs the source, so",
    "inlining can differ between the two columns. Figures are one machine's and move a few percent",
    "per run: read ratios, not digits.",
    "",
    "Throughput is operations per second in millions, with one byte of every result consumed so the",
    "call cannot be optimised away. Rows named `package.*` are this package; the other rows are",
    "competitor packages and the runtime's own functions, listed for the cost of the same surface.",
    "",
    `Randomness uses ${String(entropySamples)} samples per candidate per runtime; the method and its`,
    "limits are in `bench/entropy.ts`.",
    "",
    "- `distinct`: different random fields drawn. A repeat within the sample would show here.",
    "- `in-tick`: consecutive values inside one millisecond that strictly increase, over",
    "  same-millisecond pairs only. Pairs that span a tick order by timestamp whatever the generator",
    "  does, so counting them would measure the clock.",
    "- `peak/ms`: most values drawn in one millisecond. It decides whether a counter wraps.",
    "- `counter`: width of a leading counter advancing by exactly one, with the share of pairs",
    "  obeying it. It says nothing about how many bits an attacker can predict.",
    "- `P(1) range`: narrowest and widest share of ones across the 74 random bits.",
    "",
    'An entropy source of "unobserved" means the draw happens below JavaScript or the library',
    "captured its source before instrumentation; it states what was seen, not a finding.",
    "",
    "Not covered: memory and allocation, multi-core contention, cold start, megamorphic call sites,",
    "and randomness quality beyond these measures; that needs a battery such as PractRand.",
  ];
  lines.push("", output.trim());
  return `${lines.join("\n")}\n`;
}

await mkdir(results, { recursive: true });

const competitorLines = await drive("generation-matrix.ts", {
  UUID_SLUG_GENERATION_MS: String(competitors.durationMs),
  UUID_SLUG_GENERATION_SAMPLES: String(competitors.samples),
  UUID_SLUG_GENERATION_WARMUP_MS: String(competitors.warmupMs),
});
const records = competitorLines
  .trim()
  .split("\n")
  .map((line): ReportRecord => JSON.parse(line) as ReportRecord);
await Bun.write(join(results, "competitors.jsonl"), competitorLines);
await Bun.write(
  join(results, "competitors.md"),
  `${renderGenerationReport(records, { ...competitors, generatedOn, machine })}\n`,
);

const matrixLines = await drive("matrix.ts", {
  UUID_SLUG_ENTROPY_SAMPLES: String(entropySamples),
});
await Bun.write(join(results, "matrix.md"), matrixReport(matrixLines));
console.log(`wrote ${results}/competitors.md, competitors.jsonl, matrix.md`);
